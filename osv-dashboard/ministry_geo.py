def normalize_territory(value):
    """Match only the report's explicit administrative-belonging field."""
    text = str(value or '').strip().casefold().replace('ё', 'е')
    text = re.sub(r'\bмосковской области\b', '', text)
    text = re.sub(r'\b(?:городской|муниципальный)\s+округ\b', '', text)
    return re.sub(r'[\s.,;:]+', ' ', text).strip()


_BY_NORMALIZED_NAME = {
    normalize_territory(name): name for name, _kind in MUNICIPALITIES
}


def municipality_for_territory(value):
    """Return canonical name only for a unique exact normalized official name."""
    return _BY_NORMALIZED_NAME.get(normalize_territory(value))


def territory_aliases_for(name, observed_values):
    """Observed report labels that normalize exactly to a selected official name."""
    if name not in {item[0] for item in MUNICIPALITIES}:
        return []
    return [
        value for value in observed_values
        if municipality_for_territory(value) == name
    ]
