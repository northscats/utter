# Keep account codes readable in dense Russian financial descriptions.
def readable(text):
    return re.sub(r"(?<=[А-Яа-яЁё])(?=\d)", " ", text)


notes = [(readable(label), readable(text)) for label, text in notes]
sections = [
    (name, [[readable(value) for value in row] for row in rows], widths)
    for name, rows, widths in sections
]
# Check narrative reference codes and table shapes before exporting.
valid_refs = {row[0] for row in SOURCES[1:]}
for _, rows, widths in sections:
    assert all(len(row) == len(widths) for row in rows)
    for row in rows:
        for value in row:
            assert set(re.findall(r"\bR\d+\b", str(value))) <= valid_refs

